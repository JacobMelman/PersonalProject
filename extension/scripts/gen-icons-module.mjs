// Regenerates src/ui/icons.ts from the list below (Lucide icons, ISC licence, imported as SVG text).
import { writeFileSync } from 'node:fs';
const names = `circle-dot circle video camera flag pause play square zap shield-check lock clock timer trash-2 external-link settings download copy file-text file-code-2
file-spreadsheet file-type-2 archive mouse-pointer-click navigation info text-cursor-input send x check chevron-right chevron-down triangle-alert moon eye-off power history
layers rewind film image globe refresh-cw sparkles monitor bookmark list-checks arrow-left keyboard hard-drive scan-eye route pencil mouse-pointer-2 move-up-right minus type
blend rectangle-horizontal undo-2 redo-2 rotate-ccw grid-3x3 scissors crosshair lock-keyhole shield-alert droplets circle-check`.split(/\s+/);
const id = (n) => 'i_' + n.replace(/-/g, '_');
const out = `// GENERATED by scripts/gen-icons-module.mjs - Lucide icons (ISC) bundled as text so the extension stays offline and CSP-clean.
${names.map((n) => `import ${id(n)} from 'lucide-static/icons/${n}.svg';`).join('\n')}

const raw = {
${names.map((n) => `  '${n}': ${id(n)},`).join('\n')}
} as const;

export type IconName = keyof typeof raw;

/** Inline SVG sized by CSS (1em), coloured by currentColor. */
export function icon(name: IconName, cls = ''): string {
  return raw[name]
    .replace(/<!--[\\s\\S]*?-->\\s*/, '')
    .replace(/\\s+class="[^"]*"/, '')
    .replace(/\\s+width="24"\\s+height="24"/, '')
    .replace('<svg', \`<svg class="i \${cls}" aria-hidden="true" focusable="false"\`);
}
`;
writeFileSync(new URL('../src/ui/icons.ts', import.meta.url), out);
console.log('icons.ts regenerated:', names.length, 'icons');
